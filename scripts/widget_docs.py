"""
Write `docs/widgets/README.md` and its pictures from the widgets themselves.

Everything the page says comes from `widget.yml`, its translations and the `docs`
list of `preview.yml`, so the page cannot disagree with the widgets. Run

    python -m scripts.widget_docs

after changing a widget; a test fails while the committed page is out of date.
"""

from __future__ import annotations

import asyncio
from pathlib import Path
from typing import Any

from PIL import Image

from custom_components.opendisplay_studio.widgets import (
    BUILTIN_WIDGET_DIRECTORY,
    WidgetRegistry,
)
from custom_components.opendisplay_studio.widgets.preview import (
    MAX_PREVIEW_SIZE,
    PREVIEW_FILE,
)
from scripts.widget_devkit.scenario import (
    PreviewSize,
    Showcase,
    context_for,
    draw,
    load_preview,
    load_registry,
    load_states,
    png_bytes,
    with_options,
)

DOCS = Path("docs/widgets")
IMAGES = DOCS / "images"
README = DOCS / "README.md"
ABOUT_FILE = "about.md"
# A picture is shown at most this wide; a smaller one keeps its own size.
PICTURE_WIDTH = 380
THUMBNAIL_WIDTH = 150
TIMES = chr(0xD7)  # the multiplication sign used in sizes
GALLERY_COLUMNS = 2
# Appearance options every widget has; they are described once, at the top.
SHARED_OPTIONS = ("showFrame", "cornerRadius", "color", "background", "font")
INTRO = """\
# Widgets

A widget shows live Home Assistant data inside a dashboard. You pick *what* to show
(its **sources**), set *how* it looks (its **options**) and resize its frame; the
widget lays itself out to fit.

This page is generated by `python -m scripts.widget_docs`, so it always says what the
widgets do. To write your own widget see [the widget SDK](../widget-sdk.md).

## Options every widget has

| Option | Key | What it does |
|---|---|---|
| Show frame | `showFrame` | Draws the frame and the background. Turn it off to place the content straight onto the dashboard. |
| Corner radius | `cornerRadius` | How round the corners of the frame are. |
| Color | `color` | The color of everything drawn: text, icons, lines and the frame. |
| Background | `background` | What is filled behind it. |
| Font | `font` | Any font that comes with OpenDisplay Studio or that you installed in Settings. |

Colors are picked from the colors of the display, so white on black is two colors, and on
a display with red and yellow you can have yellow on red. A few widgets also have a
**Text size**: leave it on Auto to fit the frame, or type the size you want.
"""  # noqa: E501 - table rows cannot be wrapped


_NAMED_KINDS = {
    "boolean": "on / off",
    "opendisplay_color": "color",
    "opendisplay_font": "font",
    "opendisplay_ranges": "list of colored ranges",
}


def _type_of(selector: dict[str, Any]) -> str:
    kind, config = next(iter(selector.items()))
    if kind in _NAMED_KINDS:
        return _NAMED_KINDS[kind]
    if kind == "number":
        if "min" not in config or "max" not in config:
            return "number"
        return f"number {config['min']} to {config['max']}"
    if kind == "select":
        choices = ", ".join(f"`{option['value']}`" for option in config["options"])
        return f"one of {choices}"
    return kind


def _default_of(value: Any) -> str:
    if value is None:
        return "automatic"
    if isinstance(value, bool):
        return "on" if value else "off"
    if value == "":
        return "empty"
    return f"`{value}`"


def _source_type(selector: dict[str, Any]) -> str:
    kind, config = next(iter(selector.items()))
    domains = config.get("filter", {}).get("domain", "")
    domain = " or ".join(domains) if isinstance(domains, list) else domains
    count = "one or more" if config.get("multiple") else "one"
    return " ".join(part for part in (count, domain, kind) if part)


def _sources_table(definition: dict[str, Any]) -> list[str]:
    lines = ["| Source | What to pick | Per pick |", "|---|---|---|"]
    for source in definition["sources"]:
        extras = ", ".join(extra["label"] for extra in source["perSource"]) or "—"
        needed = "" if source["required"] else " (optional)"
        lines.append(
            f"| {source['label']}{needed} | {_source_type(source['selector'])}"
            f" | {extras} |"
        )
    return lines


def _options_tables(definition: dict[str, Any]) -> list[str]:
    """One table per section; the options every widget has are left to the top."""
    lines: list[str] = []
    for section in definition["options"]:
        fields = [
            option
            for option in section["fields"]
            if option["key"] not in SHARED_OPTIONS
        ]
        if not fields:
            continue
        lines += ["", f"**{section['section']}**", ""]
        lines += ["| Option | Key | Values | Default |", "|---|---|---|---|"]
        for option in fields:
            lines.append(
                f"| {option['label']} | `{option['key']}` "
                f"| {_type_of(option['selector'])} | {_default_of(option['default'])} |"
            )
    return lines


def _anchor(name: str) -> str:
    """Return the address GitHub gives the heading `name`."""
    return name.lower().replace(" ", "-")


def _picture(widget_id: str, number: int, showcase: Showcase, width: int) -> str:
    """Return the `<img>` of a showcase, no wider than `width` and than itself."""
    title = showcase.title.replace('"', "&quot;")
    return f'<img src="images/{widget_id}-{number}.png" alt="{title}" width="{width}">'


def _shown_width(showcase: Showcase, sizes: dict[str, PreviewSize]) -> int:
    return min(sizes[showcase.size].width, PICTURE_WIDTH)


def _cell(
    widget_id: str, number: int, showcase: Showcase, sizes: dict[str, PreviewSize]
) -> str:
    picture = _picture(widget_id, number, showcase, _shown_width(showcase, sizes))
    return (
        f'<td align="center" valign="top">{picture}<br><sub>{showcase.title}</sub></td>'
    )


def _gallery(
    widget_id: str, showcases: tuple[Showcase, ...], sizes: dict[str, PreviewSize]
) -> list[str]:
    """Return the pictures after the first as a table, the title under each."""
    cells = [
        _cell(widget_id, number, showcase, sizes)
        for number, showcase in enumerate(showcases[1:], start=2)
    ]
    if not cells:
        return []
    rows = [
        "<tr>" + "".join(cells[start : start + GALLERY_COLUMNS]) + "</tr>"
        for start in range(0, len(cells), GALLERY_COLUMNS)
    ]
    return ["### Examples", "", "<table>", *rows, "</table>"]


def _first_picture(
    widget_id: str, showcases: tuple[Showcase, ...], sizes: dict[str, PreviewSize]
) -> list[str]:
    """Return the first picture, centered, with its title under it."""
    if not showcases:
        return []
    first = showcases[0]
    picture = _picture(widget_id, 1, first, _shown_width(first, sizes))
    return [f'<p align="center">{picture}<br><sub>{first.title}</sub></p>', ""]


def _folder(root: Path, widget_id: str) -> Path:
    return root / widget_id.replace("-", "_")


def _facts(definition: dict[str, Any]) -> list[str]:
    size = definition["layout"]["defaultSize"]
    minimum = definition["layout"]["minSize"]
    return [
        "| Default size | Smallest | Id |",
        "|---|---|---|",
        (
            f"| {size['width']} {TIMES} {size['height']} px "
            f"| {minimum['width']} {TIMES} {minimum['height']} px "
            f"| `{definition['id']}` |"
        ),
    ]


def _widget_section(registry: WidgetRegistry, widget_id: str, root: Path) -> str:
    definition = next(
        item for item in registry.definitions() if item["id"] == widget_id
    )
    preview = load_preview(_folder(root, widget_id))
    sizes = {size.name: size for size in preview.sizes}
    about = _folder(root, widget_id) / ABOUT_FILE
    about_text = about.read_text(encoding="utf-8").strip() if about.is_file() else ""
    lines = [
        f"## {definition['name']}",
        "",
        f"*{definition['description']}*",
        "",
        *_facts(definition),
        "",
        *_first_picture(widget_id, preview.showcases, sizes),
        *([about_text, ""] if about_text else []),
        "### Sources",
        "",
        *_sources_table(definition),
        "",
        "### Options",
        *_options_tables(definition),
        "",
        *_gallery(widget_id, preview.showcases, sizes),
    ]
    return "\n".join(lines).rstrip("\n")


def _contents(registry: WidgetRegistry, root: Path) -> str:
    """Return a table of every widget: a small picture, its name and what it shows."""
    rows = ["## The widgets", "", "| | Widget | Shows |", "|---|---|---|"]
    for definition in sorted(registry.definitions(), key=lambda item: item["id"]):
        widget_id = definition["id"]
        has_picture = load_preview(_folder(root, widget_id)).showcases
        thumbnail = (
            f'<a href="#{_anchor(definition["name"])}">'
            f'<img src="images/{widget_id}-1.png" width="{THUMBNAIL_WIDTH}" '
            f'alt="{definition["name"]}"></a>'
            if has_picture
            else ""
        )
        link = f"[**{definition['name']}**](#{_anchor(definition['name'])})"
        rows.append(f"| {thumbnail} | {link} | {definition['description']} |")
    return "\n".join(rows)


def build_markdown(root: Path = BUILTIN_WIDGET_DIRECTORY) -> str:
    """Return the whole page for the widgets under `root`."""
    registry = load_registry(root)
    sections = [
        _widget_section(registry, widget_id, root)
        for widget_id in sorted(registry.widget_types)
    ]
    separator = "\n\n---\n\n"
    return (
        INTRO
        + "\n"
        + _contents(registry, root)
        + "\n\n---\n\n"
        + separator.join(sections)
        + "\n"
    )


def preview_bytes(image: Image.Image) -> bytes:
    """Return `image`, shrunk to fit the area of a preview when it is larger."""
    shown = image.copy()
    shown.thumbnail(MAX_PREVIEW_SIZE, Image.Resampling.LANCZOS)
    return png_bytes(shown)


async def write_images(root: Path = BUILTIN_WIDGET_DIRECTORY) -> int:
    """Draw every showcase into `docs/widgets/images`; the first is also the preview."""
    registry = load_registry(root)
    IMAGES.mkdir(parents=True, exist_ok=True)
    written = 0
    for widget_id in sorted(registry.widget_types):
        folder = _folder(root, widget_id)
        preview = load_preview(folder)
        states = load_states(folder)
        sizes = {size.name: size for size in preview.sizes}
        for number, showcase in enumerate(preview.showcases, start=1):
            size = sizes[showcase.size]
            state = with_options(states[showcase.state], showcase.options)
            palette = showcase.palette or preview.palette
            context = context_for(
                registry, widget_id, state, (size.width, size.height), palette
            )
            image, _ = await draw(context, registry.renderer(widget_id))
            png = png_bytes(image)
            (IMAGES / f"{widget_id}-{number}.png").write_bytes(png)
            if number == 1:
                # The first showcase is the widget as the list of widgets shows it.
                (folder / PREVIEW_FILE).write_bytes(preview_bytes(image))
            written += 1
    return written


def main() -> None:
    """Write the page and its pictures."""
    count = asyncio.run(write_images())
    README.write_text(build_markdown(), encoding="utf-8", newline="\n")
    print(f"Wrote {README} and {count} pictures")  # noqa: T201 - a command line tool


if __name__ == "__main__":
    main()
